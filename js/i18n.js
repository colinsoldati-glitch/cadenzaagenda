function detectInitialLang() {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (SUPPORTED_LANGS.includes(saved)) return saved;
  } catch (_) {}

  const browserLangs = navigator.languages?.length ? navigator.languages : [navigator.language || "fr"];
  for (const raw of browserLangs) {
    const code = String(raw || "").toLowerCase().split("-")[0];
    if (SUPPORTED_LANGS.includes(code)) return code;
  }
  return "fr";
}

let currentLang = detectInitialLang();
let languageChangeListeners = [];

export function getLang() {
  return currentLang;
}

export function getDateLocale() {
  return DATE_LOCALES[currentLang] || "fr-CH";
}

export function onLanguageChange(fn) {
  if (typeof fn === "function") languageChangeListeners.push(fn);
}

function resolveKey(lang, key) {
  const parts = key.split(".");
  let obj = TRANSLATIONS[lang];
  for (const p of parts) {
    if (obj && typeof obj === "object" && p in obj) obj = obj[p];
    else return undefined;
  }
  return typeof obj === "string" ? obj : undefined;
}

export function t(key, params = {}) {
  let str = resolveKey(currentLang, key);
  if (str === undefined) str = resolveKey("fr", key);
  if (str === undefined) return key;
  return str.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined && params[k] !== null ? String(params[k]) : ""));
}

export function translatePeriod(period) {
  const k = PERIOD_KEY_MAP[period];
  return k ? t(k) : (period || "");
}

export function translateFormation(formation) {
  const k = FORMATION_KEY_MAP[formation];
  return k ? t(k) : (formation || "");
}

export function applyDomTranslations() {
  document.documentElement.lang = currentLang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });

  document.querySelectorAll("[data-set-lang]").forEach((btn) => {
    const isActive = btn.dataset.setLang === currentLang;
    btn.classList.toggle("active", isActive);
    btn.setAttribute("aria-pressed", String(isActive));
  });
}

export function setLang(lang, { notify = true } = {}) {
  if (!SUPPORTED_LANGS.includes(lang)) return;
  currentLang = lang;
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch (_) {}
  applyDomTranslations();
  languageChangeListeners.forEach((fn) => {
    try { fn(lang); } catch (e) { console.error(e); }
  });
  return notify ? t("langChangedToast") : null;
}
